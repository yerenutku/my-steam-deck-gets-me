-- My Steam Deck Gets Me: Button Overlay. A Steam Deck picture whose buttons glow while pressed, so viewers of a
-- video see what the player does. A separate addon: the voice addon (MySteamDeckGetsMe) doesn't need it.
--   Pad buttons and sticks: WoW reads them itself (C_GamePad.GetDeviceMappedState, polled only while shown).
--   L4 / R4 are Steam's back buttons, unseen by WoW: the My Steam Deck Gets Me app sends Shift+F10 on L4 (toggle),
--   and R4 glows while the voice addon's card (WowVoiceIndicator) says "Listening...". L5 / R5 stay unlit.
--   /deckoverlay shows / hides it without the app.
-- The picture is drawn by design/build_wheel.py (Media/deck_overlay, deck_glow); DECK below comes from there too.

local DECK = {   -- generated by design/build_wheel.py (DECK): shape, binding, box or circle in 1024x512
  LT = { "rect", "PADLTRIGGER", 100, 36, 220, 66 },
  RT = { "rect", "PADRTRIGGER", 804, 36, 924, 66 },
  LB = { "rect", "PADLSHOULDER", 80, 68, 250, 94 },
  RB = { "rect", "PADRSHOULDER", 774, 68, 944, 94 },
  UP = { "rect", "PADDUP", 115, 140, 145, 178 },
  DOWN = { "rect", "PADDDOWN", 115, 202, 145, 240 },
  LEFT = { "rect", "PADDLEFT", 77, 175, 117, 205 },
  RIGHT = { "rect", "PADDRIGHT", 143, 175, 183, 205 },
  Y = { "round", "PAD4", 894, 150, 18 },
  X = { "round", "PAD3", 854, 190, 18 },
  B = { "round", "PAD2", 934, 190, 18 },
  A = { "round", "PAD1", 894, 230, 18 },
  VIEW = { "rect", "PADBACK", 246, 130, 284, 152 },
  MENU = { "rect", "PADFORWARD", 740, 130, 778, 152 },
  LS = { "stick", "PADLSTICK", 225, 215, 40 },
  RS = { "stick", "PADRSTICK", 799, 215, 40 },
  L4 = { "rect", nil, 70, 474, 160, 504 },
  L5 = { "rect", nil, 170, 474, 260, 504 },
  R4 = { "rect", nil, 864, 474, 954, 504 },
  R5 = { "rect", nil, 764, 474, 854, 504 },
}
local MEDIA = "Interface\\AddOns\\MySteamDeckGetsMeOverlay\\Media\\"
local SCALE = 0.375                                      -- 1024x512 picture -> 384x192 on screen
local DB

local overlay = CreateFrame("Frame", "MySteamDeckGetsMeOverlayFrame", UIParent)
overlay:SetSize(1024 * SCALE, 512 * SCALE)
overlay:SetPoint("LEFT", 16, -60)
overlay:SetFrameStrata("HIGH")
overlay:Hide()
local base = overlay:CreateTexture(nil, "BACKGROUND")
base:SetAllPoints()
base:SetTexture(MEDIA .. "deck_overlay")

local parts, padIndex = {}, {}
for name, d in pairs(DECK) do
  local shape, binding = d[1], d[2]
  local t = overlay:CreateTexture(nil, "ARTWORK")
  if shape == "rect" then
    t:SetColorTexture(0.35, 1, 0.35, 0.55)
    t:SetPoint("TOPLEFT", d[3] * SCALE, -d[4] * SCALE)
    t:SetSize((d[5] - d[3]) * SCALE, (d[6] - d[4]) * SCALE)
  else
    t:SetTexture(MEDIA .. "deck_glow")
    t:SetVertexColor(0.35, 1, 0.35, 0.9)
    local size = (d[5] * 2 + 22) * SCALE
    t:SetSize(size, size)
    t:SetPoint("CENTER", overlay, "TOPLEFT", d[3] * SCALE, -d[4] * SCALE)
  end
  t:Hide()
  local part = { tex = t, binding = binding, shape = shape, d = d }
  if shape == "stick" then
    part.dot = overlay:CreateTexture(nil, "OVERLAY")
    part.dot:SetTexture(MEDIA .. "deck_glow")
    part.dot:SetVertexColor(0.95, 0.85, 0.5, 1)
    part.dot:SetSize(52 * SCALE, 52 * SCALE)
  end
  parts[name] = part
end

local function buttonIndex(binding)                      -- the pad's button number for a binding name (cached)
  if padIndex[binding] == nil then
    local ok, i = pcall(C_GamePad.ButtonBindingToIndex, binding)
    padIndex[binding] = ok and tonumber(i) and i + 1 or false
  end
  return padIndex[binding]
end

local function listening()                               -- the voice addon's card says "Listening..." (R4 held)
  local card = _G.WowVoiceIndicator
  if not (card and card:IsShown()) then return false end
  for _, region in ipairs({ card:GetRegions() }) do
    if region.GetText and region:GetText() == "Listening..." then return true end
  end
  return false
end

local l4Flash = 0
overlay:SetScript("OnUpdate", function()
  local ok, state = pcall(C_GamePad.GetDeviceMappedState)
  local buttons = ok and type(state) == "table" and state.buttons or {}
  local sticks = ok and type(state) == "table" and state.sticks or {}
  for name, part in pairs(parts) do
    local on = false
    if part.binding then
      local i = buttonIndex(part.binding)
      on = i and buttons[i] and true or false
    end
    if name == "R4" then on = listening() end
    if name == "L4" then on = GetTime() < l4Flash end
    if part.shape == "stick" then
      local st = sticks[name == "LS" and 1 or 2]
      local x, y = st and st.x or 0, st and st.y or 0
      part.dot:ClearAllPoints()
      part.dot:SetPoint("CENTER", overlay, "TOPLEFT", (part.d[3] + x * 26) * SCALE, -(part.d[4] - y * 26) * SCALE)
      on = on or math.abs(x) > 0.3 or math.abs(y) > 0.3
    end
    part.tex:SetShown(on)
  end
end)

local function toggle()
  overlay:SetShown(not overlay:IsShown())
  if DB then DB.shown = overlay:IsShown() end
  l4Flash = GetTime() + 0.3
end

local key = CreateFrame("Button", "MySteamDeckGetsMeOverlayToggle", UIParent)   -- Shift+F10 = L4 (the app)
key:SetScript("OnClick", toggle)
local events = CreateFrame("Frame")
events:RegisterEvent("ADDON_LOADED")
events:RegisterEvent("PLAYER_LOGIN")
events:SetScript("OnEvent", function(_, event, name)
  if event == "ADDON_LOADED" and name == "MySteamDeckGetsMeOverlay" then
    MySteamDeckGetsMeOverlayDB = MySteamDeckGetsMeOverlayDB or {}
    DB = MySteamDeckGetsMeOverlayDB
  elseif event == "PLAYER_LOGIN" then
    SetOverrideBindingClick(events, true, "SHIFT-F10", "MySteamDeckGetsMeOverlayToggle")
    if DB and DB.shown then overlay:Show() end
  end
end)

SLASH_DECKOVERLAY1 = "/deckoverlay"
SlashCmdList.DECKOVERLAY = toggle
